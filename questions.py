def all_levels(age_key: str) -> list[str]:
    """Жас тобының барлық мүмкін деңгейлері (ең төменгіден жоғарыға), қазақша."""
    g = AGE_GROUPS[age_key]
    return [g["zero_level"]] + [b["level"] for b in g["blocks"]]


def all_levels_ru(age_key: str) -> list[str]:
    """Сол деңгейлердің орысша атаулары (студентке көрсетіледі)."""
    g = AGE_GROUPS[age_key]
    return [g["zero_level_ru"]] + [b["level_ru"] for b in g["blocks"]]


def level_ru(age_key: str, level: str) -> str:
    """Қазақша деңгей атауы -> орысша. Ескі нәтиже болса, сол күйінде қайтарады."""
    levels = all_levels(age_key)
    return all_levels_ru(age_key)[levels.index(level)] if level in levels else level


def pass_ratio(age_key: str) -> float:
    """Жас тобының өту шегі."""
    return AGE_GROUPS[age_key].get("pass_ratio", PASS_RATIO)
